export const getTeamTheme = (teamQuery) => {
  if (!teamQuery) return defaultTheme;

  const query = teamQuery.toString().trim().toLowerCase();

  // 1. Direct Abbreviation Match (e.g., "KC", "SF", "GB")
  const upperQuery = query.toUpperCase();
  if (NFL_TEAMS[upperQuery]) {
    return NFL_TEAMS[upperQuery];
  }

  // 2. Exact Name, City, or Mascot Match
  for (const key of Object.keys(NFL_TEAMS)) {
    const team = NFL_TEAMS[key];
    if (
      team.name.toLowerCase() === query ||
      team.mascot.toLowerCase() === query ||
      team.city.toLowerCase() === query
    ) {
      return team;
    }
  }

  // 3. Whole-word / Substring Matching against Full Team Name
  for (const key of Object.keys(NFL_TEAMS)) {
    const team = NFL_TEAMS[key];
    const teamFullName = team.name.toLowerCase();
    const teamMascot = team.mascot.toLowerCase();

    if (teamFullName.includes(query) || query.includes(teamMascot) || query.includes(teamFullName)) {
      return team;
    }
  }

  return defaultTheme;
};